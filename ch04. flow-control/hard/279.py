# 직장인 여부 → 연봉 → 신용등급 → 연봉 재검사 순서로 if를 중첩하세요.
is_employed = input() == "True"
salary = int(input())
credit_grade = int(input())

# 직장인이면 연봉 확인하기
if is_employed:
    # 연봉 3000만원 이상이면 신용등급 확인하기
    if salary >= 3000:
        # 신용등급 4등급 이상(4~10)이면 연봉 재검사하기
        if 4 <= credit_grade <= 10:
            # 연봉 5000만원 미만이면 "대출 한도: 1000만원"
            if salary < 5000:
                print("대출 한도: 1000만원")
            # 연봉 5000만원 이상이면 "대출 한도: 3000만원"
            else:
                print("대출 한도: 3000만원")
        # 신용등급 3등급 이하(1~3)이면 "대출 한도: 5000만원"
        else:
            print("대출 한도: 5000만원")
    # 연봉 3000만원 미만이면 "연봉 조건 미달" 출력하기
    else:
        print("연봉 조건 미달")
# 직장인이 아니면 "직장인 확인 필요" 출력하기
else:
    print("직장인 확인 필요")