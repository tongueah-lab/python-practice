# 필기 합격일 때만 실기 점수를 input()으로 추가로 받으세요.
written = int(input())

# 필기가 60점 이상이면 첫 줄 "필기 합격!" 출력하기
if written >= 60:
    print("필기 합격!")
    # 실기 점수 변수 추가 입력하기
    play_score = int(input())
    # 실기 70점 이상이면 "최종 합격입니다!" 출력하기
    if play_score >= 70:
        print("최종 합격입니다!")
    # 실기 70점 미만이면 "실기 불합격입니다. 실기 재시험 대상입니다."
    else:
        print("실기 불합격입니다. 실기 재시험 대상입니다.")
# 필기가 60점 미만이면 "필기 불합격입니다. 필기부터 다시 응시하세요." 출력하기
else:
    print("필기 불합격입니다. 필기부터 다시 응시하세요.")