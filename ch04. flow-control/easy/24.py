# 나이와 티켓 두 값을 먼저 입력받고, 중첩 if문으로 판정하세요.
age = int(input())
ticket = input()

# 18세 이상이면 티켓을 확인한다.
if age >= 18:
    # 티켓이 "Y"이면 "입장 가능합니다."를 출력하기
    if ticket == "Y":
        print("입장 가능합니다.")
    # 티켓이 "N"이면 "티켓을 구매해주세요."를 출력하기
    else:
        print("티켓을 구매해주세요.")
# 18세 미만이면 "18세 미만은 입장할 수 없습니다."를 출력하기
else:
    print("18세 미만은 입장할 수 없습니다.")