# 무게 판정 → 옵션 입력 → 최종 배송 방식 출력.
weight = float(input())
option = input()

# 2kg이상이면 옵션을 입력받는다
if weight >= 2:
    # 빠른 배송에 Y를 하면 "택배(빠른 배송) - 5000원"을 출력하기
    if option == "Y":
        print("택배(빠른 배송) - 5000원")
    # 일반에 N를 하면 "택배(일반 배송) - 3000원"을 출력하기
    elif option == "N":
        print("택배(일반 배송) - 3000원")
# 무게가 2kg미만이면 옵션을 받는다
else:
    # 등기에 Y를 하면 "우편(등기) - 2000원"을 출력하기
    if option == "Y":
        print("우편(등기) - 2000원")
    # 일반에 N를 하면 "우편(일반) - 1000원"을 출력하기
    elif option == "N":
        print("우편(일반) - 1000원")