# 130cm 이상일 때만 보호자 입력을 받고, 그 안에서 다시 150cm 기준으로 나누세요.
height = int(input())

# 키 130cm 이상이면 보호자 동반 여부 확인하기
if height >= 130:
    # 보호자 동반 여부 추가로 입력받기
    guardian = input()
    # 보호자가 Y이면 "보호자와 함께 탑승 가능합니다." 출력하기
    if guardian == "Y":
        print("보호자와 함께 탑승 가능합니다.")
    # 보호자가 N이면 키가 150cm이상인지 확인하기
    elif guardian == "N":
        # 키 150cm 이상이면 "혼자 탑승 가능합니다." 출력하기
        if height >= 150:
            print("혼자 탑승 가능합니다.")
        # 키 150cm 미만이면 "탑승할 수 없습니다." 출력하기
        else:
            print("보호자가 필요합니다.")
# 키 130cm 미만이면 "탑승할 수 없습니다." 출력하기
else:
    print("탑승할 수 없습니다.")